#pragma once

#include "utils/defs.hpp"
#include "bytecode/bc_common.hpp"

#include <vector>
#include <unordered_map>
#include <cassert>
#include <memory>

namespace bloop::metadata {

	struct ParserMetadata {
		bloop::BloopUInt m_uNumLambdas{};
	};

	struct VMMetadata {

		[[maybe_unused]] bloop::BloopIndex AddChunk(const bloop::bc::Chunk& data) {
			const auto idx = static_cast<bloop::BloopIndex>(m_oChunks.size());
			m_oChunks.emplace_back(data).m_uId = idx;
			return idx;
		}
		void AddFunction(const bloop::bc::Function& data, bloop::BloopIndex idx) {
			assert(idx < m_oFunctions.size());
			m_oFunctions[idx] = data;
		}

		std::vector<bloop::bc::Chunk> m_oChunks;
		std::vector<bloop::bc::Function> m_oFunctions; // references m_oFunctionDebugInfo
		bloop::bc::Chunk* m_pGlobalChunk{};
	};

	struct Metadata {

		//contains every line of the source code (of every file, one after another)
		//VMMetadata references this in debug builds
		std::vector<bloop::BloopStringView> m_oLineMap; 

		// one per file in the program (the main file and the modules it imports).
		// lines are numbered across all files, so the lines of a file are
		// [m_uFirstLine, m_uFirstLine + number of lines in the file)
		struct SourceFile {
			bloop::BloopString m_sName; // as shown in error messages
			std::shared_ptr<const bloop::BloopString> m_pSource; // m_oLineMap points into this
			bloop::BloopSize m_uFirstLine{};
		};
		std::vector<SourceFile> m_oSourceFiles;

		[[nodiscard]] const SourceFile* FindSourceFile(bloop::BloopSize line) const noexcept {
			const SourceFile* result{};
			for (const auto& file : m_oSourceFiles) {
				if (file.m_uFirstLine > line)
					break;
				result = &file;
			}
			return result;
		}

		// "line:column", or "file:line:column" when the program has more than one file
		[[nodiscard]] bloop::BloopString FormatPosition(const bloop::CodePosition& pos) const {
			const auto [line, column] = pos;
			const auto* file = m_oSourceFiles.size() > 1u ? FindSourceFile(line) : nullptr;
			if (!file)
				return std::to_string(line) + ':' + std::to_string(column);

			return file->m_sName + ':' + std::to_string(line - file->m_uFirstLine + 1u) + ':' + std::to_string(column);
		}

		struct FunctionDebugInfo {

			//references m_oLineMap
			bloop::BloopIndex m_uId{};
			bloop::BloopString m_sName;
			bloop::BloopUInt m_uStartLine{};
			bloop::BloopUInt m_uEndLine{};

		};

		std::vector<FunctionDebugInfo> m_oFunctionDebugInfo;
		std::unordered_map<bloop::BloopString, FunctionDebugInfo*> m_oFunctionTable;
		bloop::BloopIndex m_uNumGlobals{};

		// prints the generated bytecode and how long the script ran (for working on the language itself)
		bloop::BloopBool m_bDebugOutput{};

		ParserMetadata m_oParserData;
		VMMetadata m_oVMData;
	};

}